export const getAllWords = (): Word[] => words;

// 根据ID获取单词
export const getWordById = (id: string): Word | undefined => {
  return words.find(word => word.id === id);
};

// 随机获取指定数量的单词
export const getRandomWords = (count: number, excludeIds: string[] = []): Word[] => {
  const availableWords = words.filter(word => !excludeIds.includes(word.id));
  const shuffled = [...availableWords].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(count, shuffled.length));
};
